-- 楽曲リクエストの「自分の投稿」取り消し用トークン
--
-- ログイン機能がないため、投稿時に発行した推測不可能なトークン(256bit)で本人性を示す。
-- サーバーは SHA-256 ハッシュのみを保持し、生トークンは投稿レスポンスで1回だけ返して
-- クライアント(localStorage)が保管する。ID は連番で総当たり可能なため ID だけでは判定しない。
--
-- この列が NULL の行 = トークン方式の導入前に投稿されたデータ。
-- 本人確認できないため自己削除は不可（管理画面からの削除は従来どおり可能）。
--
-- 適用（本番 D1）:
--   npx wrangler d1 execute <DB名> --remote --file=d1/migrations/0002_song_request_owner_token.sql
--
-- 未適用のままでも投稿は失敗しない（リポジトリ側が列なしSQLにフォールバックする）。
-- ただしトークンが保存されないため、その間の投稿は自己取り消しができない。

ALTER TABLE song_requests ADD COLUMN owner_token_hash TEXT;
